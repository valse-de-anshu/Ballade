#!/usr/bin/env bash
# Apply cursor theme + size. Usage: set-cursor-theme.sh <theme> [size]
# Handles GNOME/GTK, KDE/Qt, X11/Xresources, Hyprland, and Niri.
set -u

theme="$1"
size="${2:-24}"
[[ -z "$theme" ]] && { echo "usage: $0 <cursor-theme> [size]" >&2; exit 1; }

# 1. GNOME / GTK settings (toggle to trigger live cache invalidation for updated themes)
gsettings set org.gnome.desktop.interface cursor-theme "default" 2>/dev/null || true
gsettings set org.gnome.desktop.interface cursor-theme "$theme" 2>/dev/null || true
gsettings set org.gnome.desktop.interface cursor-size "$size" 2>/dev/null || true

# 2. KDE / Qt platform theme settings (kcminputrc + kdeglobals)
if command -v kwriteconfig6 >/dev/null 2>&1; then
    kwriteconfig6 --file kcminputrc --group Mouse --key cursorTheme "$theme" 2>/dev/null || true
    kwriteconfig6 --file kcminputrc --group Mouse --key cursorSize "$size" 2>/dev/null || true
    kwriteconfig6 --file kdeglobals --group Mouse --key cursorTheme "$theme" 2>/dev/null || true
    kwriteconfig6 --file kdeglobals --group Mouse --key cursorSize "$size" 2>/dev/null || true
fi

# 3. Default cursor inheritance for X11/legacy apps
mkdir -p "$HOME/.icons/default"
cat >"$HOME/.icons/default/index.theme" <<EOF
[Icon Theme]
Name=Default
Comment=Default cursor theme (generated by shell settings)
Inherits=$theme
EOF

# 4. X11 / XWayland xrdb resources
if command -v xrdb >/dev/null 2>&1; then
    printf "Xcursor.theme: %s\nXcursor.size: %s\n" "$theme" "$size" | xrdb -merge 2>/dev/null || true
fi

# 5. Hyprland runtime apply (toggle to force compositor cursor reload)
if command -v hyprctl >/dev/null 2>&1 && [ -n "${HYPRLAND_INSTANCE_SIGNATURE:-}" ]; then
    hyprctl setcursor default "$size" 2>/dev/null || true
    hyprctl setcursor "$theme" "$size" 2>/dev/null || true
    hyprctl eval "hl.env('XCURSOR_THEME', '$theme'); hl.env('XCURSOR_SIZE', '$size'); hl.env('HYPRCURSOR_THEME', '$theme'); hl.env('HYPRCURSOR_SIZE', '$size')" 2>/dev/null || true
fi

# 6. Hyprland persistence in ~/.config/hypr/custom
for env_file in "$HOME/.config/hypr/custom/env.lua"; do
    if [ -f "$env_file" ]; then
        sed -i -E "s|hl\.env\(\"XCURSOR_THEME\", \".*\"|hl.env(\"XCURSOR_THEME\", \"$theme\"|" "$env_file"
        sed -i -E "s|hl\.env\(\"XCURSOR_SIZE\", \".*\"|hl.env(\"XCURSOR_SIZE\", \"$size\"|" "$env_file"
        if grep -q 'hl.env("HYPRCURSOR_THEME"' "$env_file"; then
            sed -i -E "s|hl\.env\(\"HYPRCURSOR_THEME\", \".*\"|hl.env(\"HYPRCURSOR_THEME\", \"$theme\"|" "$env_file"
        else
            sed -i -E "/hl\.env\(\"XCURSOR_THEME\"/a hl.env(\"HYPRCURSOR_THEME\", \"$theme\")" "$env_file"
        fi
        if grep -q 'hl.env("HYPRCURSOR_SIZE"' "$env_file"; then
            sed -i -E "s|hl\.env\(\"HYPRCURSOR_SIZE\", \".*\"|hl.env(\"HYPRCURSOR_SIZE\", \"$size\"|" "$env_file"
        else
            sed -i -E "/hl\.env\(\"XCURSOR_SIZE\"/a hl.env(\"HYPRCURSOR_SIZE\", \"$size\")" "$env_file"
        fi
    fi
done

for exec_file in "$HOME/.config/hypr/custom/execs.lua"; do
    if [ -f "$exec_file" ]; then
        sed -i -E "s|hyprctl setcursor [^ \"'\\]+ [0-9]+|hyprctl setcursor $theme $size|" "$exec_file"
    fi
done

# Also keep ballade/hyprland-custom in sync if present
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BALLADE_DIR="$(cd "$SCRIPT_DIR/../.." && pwd)"

if [ -f "$BALLADE_DIR/hyprland-custom/env.lua" ]; then
    sed -i -E "s|hl\.env\(\"XCURSOR_THEME\", \".*\"|hl.env(\"XCURSOR_THEME\", \"$theme\"|" "$BALLADE_DIR/hyprland-custom/env.lua"
    sed -i -E "s|hl\.env\(\"XCURSOR_SIZE\", \".*\"|hl.env(\"XCURSOR_SIZE\", \"$size\"|" "$BALLADE_DIR/hyprland-custom/env.lua"
    if grep -q 'hl.env("HYPRCURSOR_THEME"' "$BALLADE_DIR/hyprland-custom/env.lua"; then
        sed -i -E "s|hl\.env\(\"HYPRCURSOR_THEME\", \".*\"|hl.env(\"HYPRCURSOR_THEME\", \"$theme\"|" "$BALLADE_DIR/hyprland-custom/env.lua"
    else
        sed -i -E "/hl\.env\(\"XCURSOR_THEME\"/a hl.env(\"HYPRCURSOR_THEME\", \"$theme\")" "$BALLADE_DIR/hyprland-custom/env.lua"
    fi
    if grep -q 'hl.env("HYPRCURSOR_SIZE"' "$BALLADE_DIR/hyprland-custom/env.lua"; then
        sed -i -E "s|hl\.env\(\"HYPRCURSOR_SIZE\", \".*\"|hl.env(\"HYPRCURSOR_SIZE\", \"$size\"|" "$BALLADE_DIR/hyprland-custom/env.lua"
    else
        sed -i -E "/hl\.env\(\"XCURSOR_SIZE\"/a hl.env(\"HYPRCURSOR_SIZE\", \"$size\")" "$BALLADE_DIR/hyprland-custom/env.lua"
    fi
fi

if [ -f "$BALLADE_DIR/hyprland-custom/execs.lua" ]; then
    sed -i -E "s|hyprctl setcursor [^ \"'\\]+ [0-9]+|hyprctl setcursor $theme $size|" "$BALLADE_DIR/hyprland-custom/execs.lua"
fi

exit 0
